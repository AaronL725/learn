import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
const skill = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export function projectConfig(config, node, script, project = process.cwd()) {
  function set(section, key, value) {
    const heading = `[${section}]`;
    const start = config.indexOf(heading);
    if (start < 0) { config += `\n${heading}\n${key} = ${value}\n`; return; }
    const bodyStart = start + heading.length;
    const next = /\n\s*\[/.exec(config.slice(bodyStart));
    const end = next ? bodyStart + next.index : config.length;
    let body = config.slice(bodyStart, end);
    const pattern = new RegExp(`^${key}\\s*=.*$`, 'm');
    body = pattern.test(body) ? body.replace(pattern, () => `${key} = ${value}`) : body + `\n${key} = ${value}\n`;
    config = config.slice(0, bodyStart) + body + config.slice(end);
  }
  set('features', 'default_mode_request_user_input', 'true');
  set('agents', 'enabled', 'true');
  set('mcp_servers.learn', 'command', JSON.stringify(node));
  set('mcp_servers.learn', 'args', JSON.stringify([script]));
  set('mcp_servers.learn', 'cwd', JSON.stringify(project));
  set('mcp_servers.learn', 'startup_timeout_sec', '20');
  set('mcp_servers.learn', 'tool_timeout_sec', '120');
  return config;
}
const quote = value => "'" + value.replaceAll("'", "'\\''") + "'";
export function configureProject(project = process.cwd()) {
  const root = fs.realpathSync(project);
  fs.mkdirSync(path.join(root, '.codex/agents'), { recursive: true });
  for (const name of ['researcher', 'mermaid-maker', 'svg-maker']) {
    const target = path.join(root, '.codex/agents', `${name}.toml`);
    if (fs.existsSync(target) && !fs.readFileSync(target, 'utf8').startsWith('# Learning role generated by ai-learning')) throw new Error(`Existing custom agent ${target} was preserved. Resolve the role name before teaching.`);
  }
  const configPath = path.join(root, '.codex/config.toml');
  const config = fs.existsSync(configPath) ? fs.readFileSync(configPath, 'utf8') : 'web_search = "live"\n\n[agents]\nenabled = true\n';
  fs.writeFileSync(configPath, projectConfig(config, process.execPath, path.join(skill, 'scripts/learn.mjs'), root));
  const hook = { type: 'command', command: `cd ${quote(root)} && ${quote(process.execPath)} ${quote(path.join(skill, 'scripts/md-log.mjs'))} # ai-learning hook`, timeout: 3 };
  const hooksPath = path.join(root, '.codex/hooks.json');
  const hooks = fs.existsSync(hooksPath) ? JSON.parse(fs.readFileSync(hooksPath, 'utf8')) : { description: 'Mirror only learner/chat prose and learning Q&A into the Obsidian note.', hooks: {} };
  for (const event of ['SessionStart', 'SessionEnd']) {
    const groups = hooks.hooks[event] ||= [];
    const existing = groups.flatMap(g => g.hooks || []).find(h => h.command?.endsWith(' # ai-learning hook') || h.command?.includes(JSON.stringify(path.join(root, 'extensions/md-log.mjs'))));
    if (existing) Object.assign(existing, hook); else groups.push({ hooks: [hook] });
  }
  fs.writeFileSync(hooksPath, JSON.stringify(hooks, null, 2) + '\n');
  for (const name of ['researcher', 'mermaid-maker', 'svg-maker']) {
    const target = path.join(root, '.codex/agents', `${name}.toml`);
    const template = fs.readFileSync(path.join(skill, 'agents', `${name}.toml`), 'utf8');
    // Codex validates each role's MCP table as a complete transport, even when disabled.
    const transport = `command = ${JSON.stringify(process.execPath)}\nargs = ${JSON.stringify([path.join(skill, 'scripts/learn.mjs')])}\ncwd = ${JSON.stringify(root)}\nstartup_timeout_sec = 20\ntool_timeout_sec = 120\n`;
    fs.writeFileSync(target, template + transport);
  }
  const note = path.join(root, 'learning-log.md');
  if (!fs.existsSync(note)) fs.writeFileSync(note, '# Learning log\n', { flag: 'wx' });
  return root;
}
if (process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.length && (args[0] !== '--project' || args.length !== 2)) throw new Error('Usage: node <skill>/scripts/setup.mjs [--project <existing-project-directory>]');
  const dir = path.join(skill, 'scripts/visual-tools');
  execFileSync('npm', ['ci', '--prefix', dir, '--omit=dev', '--ignore-scripts', '--no-audit', '--no-fund'], { stdio: 'inherit', env: { ...process.env, PUPPETEER_SKIP_DOWNLOAD: '1' } });
  const project = configureProject(args[1] || process.cwd());
  console.log(`Configured ${project}. Open Codex there and use /hooks to trust the two learning log hooks. Re-run setup after moving the skill.`);
}
